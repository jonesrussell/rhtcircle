<?php

declare(strict_types=1);

// Pre-release coordination plumbing (waaseyaa/framework#2136): generates the
// gitignored composer.local.json mapping every waaseyaa/* package to a local
// framework checkout as version 0.1.0-alpha.277, so `composer update` resolves
// the coordinated release before it exists on Packagist. Usage:
//   php bin/devtools-link-framework.php [path-to-framework]   (default ../waaseyaa)
// Delete composer.local.json after v0.1.0-alpha.277 is cut — composer.json
// carries the identical pins against Packagist.

$base = '../waaseyaa';
$writeCiManifest = false;
foreach (array_slice($argv, 1) as $argument) {
    if ($argument === '--ci') {
        $writeCiManifest = true;
        continue;
    }
    $base = $argument;
}
$ver = '0.1.0-alpha.277';
$versions = [];
foreach (glob($base . '/packages/*/composer.json') ?: [] as $cj) {
    $name = json_decode((string) file_get_contents($cj), true)['name'] ?? null;
    if (is_string($name)) {
        $versions[$name] = $ver;
    }
}
ksort($versions);
if ($versions === []) {
    fwrite(STDERR, "No framework packages found under $base\n");
    exit(1);
}
$repositories = [
    ['type' => 'path', 'url' => $base, 'options' => ['symlink' => true, 'versions' => ['waaseyaa/framework' => $ver]]],
    ['type' => 'path', 'url' => $base . '/packages/*', 'options' => ['symlink' => true, 'versions' => $versions]],
];

file_put_contents(__DIR__ . '/../composer.local.json', json_encode([
    '_comment' => 'Generated by bin/devtools-link-framework.php — local/CI framework linkage until v0.1.0-alpha.277 is released.',
    'repositories' => $repositories,
], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n");
echo count($versions) . " packages linked from $base\n";

if ($writeCiManifest) {
    $rootPath = __DIR__ . '/../composer.json';
    $root = json_decode((string) file_get_contents($rootPath), true, flags: JSON_THROW_ON_ERROR);
    $root['repositories'] = array_merge($repositories, $root['repositories'] ?? []);
    file_put_contents(
        __DIR__ . '/../composer.ci.json',
        json_encode($root, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR) . "\n",
    );
    echo "CI Composer manifest written to composer.ci.json\n";
}
